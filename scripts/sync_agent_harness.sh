#!/usr/bin/env bash
# Write each agent harness file from its source.
#
#   scripts/sync_agent_harness.sh           write the copies and the adapters
#   scripts/sync_agent_harness.sh --check   exit 1 when a file is missing,
#                                           differs from its source, or is a
#                                           symlink
#
# The repository keeps copies and no symlinks, because some container
# setups stop when the bind mount tree holds a symlink.
#
# Unlike pubready, the Codex and opencode adapters are not edited by hand: this
# script builds them from the skill source, so the three guides cannot drift.
#
# | Source                            | Written file                       | Read by               |
# |-----------------------------------|------------------------------------|-----------------------|
# | AGENTS.md                         | CLAUDE.md                          | Claude Code           |
# | skills/claude-code/SKILL.md       | .claude/skills/<name>/SKILL.md     | Claude Code, opencode |
# | skills/claude-code/SKILL.md       | .agents/skills/<name>/SKILL.md     | Codex, opencode, pi   |
# | skills/claude-code/SKILL.md       | skills/codex/AGENTS.md             | Codex                 |
# | skills/claude-code/SKILL.md       | skills/opencode/AGENTS.md          | opencode              |
# | skills/opencode/command/<name>.md | .opencode/command/<name>.md        | opencode              |
# | skills/pi/prompts/<name>.md       | .pi/prompts/<name>.md              | pi                    |
set -euo pipefail

cd "$(dirname "$0")/.."

skill=skills/claude-code/SKILL.md
name="$(sed -n 's/^name: *//p' "$skill" | head -n 1)"
if [ -z "$name" ]; then
  echo "$skill has no 'name:' field." >&2
  exit 1
fi

codex_install="Codex reads the nearest \`AGENTS.md\` from the working directory up. The root \`AGENTS.md\` of this repository points to this file, so no install step is necessary. Do not replace the root \`AGENTS.md\` with a link to this file, because the root file also holds the rules for work on the repository."
opencode_install="opencode loads this file through the \`instructions\` list in \`opencode.json\`. The \`/$name\` command source is \`skills/opencode/command/$name.md\`, and its copy is \`.opencode/command/$name.md\`."

# Print the guide body: the skill without its frontmatter, its title line and
# its Install section.
guide_body() {
  awk 'NR == 1 && /^---$/ {front = 1; next}
       front == 1 {if (/^---$/) front = 2; next}
       !title && /^$/ {next}
       !title && /^# / {title = 1; next}
       /^## Install$/ {exit}
       {print}' "$skill"
}

# Print one adapter: a generated-file note, its title, the guide body and its
# install note.
adapter() {
  local harness="$1" install="$2"
  printf '<!-- Generated by scripts/sync_agent_harness.sh from %s. Do not edit. -->\n\n' "$skill"
  printf '# %s (%s adapter)\n' "$name" "$harness"
  guide_body
  printf '## Install\n\n%s\n' "$install"
}

pairs=(
  "AGENTS.md CLAUDE.md"
  "$skill .claude/skills/$name/SKILL.md"
  "$skill .agents/skills/$name/SKILL.md"
  "skills/opencode/command/$name.md .opencode/command/$name.md"
  "skills/pi/prompts/$name.md .pi/prompts/$name.md"
)

mode="${1:-write}"
status=0

for pair in "${pairs[@]}"; do
  read -r src dst <<<"$pair"
  if [ ! -f "$src" ]; then
    echo "missing source: $src" >&2
    status=1
    continue
  fi
  if [ "$mode" = "--check" ]; then
    if [ -L "$dst" ] || [ -L "$(dirname "$dst")" ] || ! cmp -s "$src" "$dst"; then
      echo "out of date: $dst (run scripts/sync_agent_harness.sh)" >&2
      status=1
    fi
  else
    mkdir -p "$(dirname "$dst")"
    cp "$src" "$dst"
    echo "wrote $dst"
  fi
done

for target in codex opencode; do
  dst="skills/$target/AGENTS.md"
  if [ "$target" = codex ]; then
    content="$(adapter Codex "$codex_install")"
  else
    content="$(adapter opencode "$opencode_install")"
  fi
  if [ "$mode" = "--check" ]; then
    if [ ! -f "$dst" ] || [ "$content" != "$(cat "$dst")" ]; then
      echo "out of date: $dst (run scripts/sync_agent_harness.sh)" >&2
      status=1
    fi
  else
    printf '%s\n' "$content" > "$dst"
    echo "wrote $dst"
  fi
done

if [ "$mode" = "--check" ] && git rev-parse --git-dir >/dev/null 2>&1; then
  # Check only the files that git tracks. A git-ignored tool install, such as
  # the node_modules that opencode writes into .opencode/, is not checked.
  links="$(git ls-files -s -- CLAUDE.md .claude .agents .opencode .pi skills \
    | awk '$1 == "120000" {print $4}')"
  if [ -n "$links" ]; then
    echo "symlinks are not allowed in the harness paths:" >&2
    printf '%s\n' "$links" >&2
    status=1
  fi
fi

exit "$status"
